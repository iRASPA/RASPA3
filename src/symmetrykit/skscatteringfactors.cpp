std::optional<double> SKScatteringFactors::xray(std::size_t atomicNumber, double sSquared)
{
  if (atomicNumber == 0 || atomicNumber > maximumAtomicNumber) return std::nullopt;

  const XRayCoefficients& coefficients = xrayCoefficients[atomicNumber];
  double factor = coefficients.c;
  for (std::size_t i = 0; i < coefficients.a.size(); ++i)
  {
    factor += coefficients.a[i] * std::exp(-coefficients.b[i] * sSquared);
  }
  return factor;
}

std::optional<double> SKScatteringFactors::electron(std::size_t atomicNumber, double sSquared)
{
  if (atomicNumber == 0 || atomicNumber > maximumAtomicNumber) return std::nullopt;

  const ElectronCoefficients& coefficients = electronCoefficients[atomicNumber];
  if (std::ranges::all_of(coefficients.a, [](double a) { return a == 0.0; })) return std::nullopt;

  double factor = 0.0;
  for (std::size_t i = 0; i < coefficients.a.size(); ++i)
  {
    factor += coefficients.a[i] * std::exp(-coefficients.b[i] * sSquared);
  }
  return factor;
}

std::optional<double> SKScatteringFactors::neutron(std::size_t atomicNumber)
{
  if (atomicNumber == 0 || atomicNumber > maximumAtomicNumber) return std::nullopt;
  return neutronScatteringLengths[atomicNumber];
}

std::optional<double> SKScatteringFactors::scatteringFactor(Radiation radiation, std::size_t atomicNumber,
                                                            double sSquared)
{
  switch (radiation)
  {
    case Radiation::XRay:
      return xray(atomicNumber, sSquared);
    case Radiation::Neutron:
      return neutron(atomicNumber);
    case Radiation::Electron:
      return electron(atomicNumber, sSquared);
  }
  return std::nullopt;
}

std::complex<double> SKScatteringFactors::anomalous(std::size_t atomicNumber, Anode anode)
{
  if (atomicNumber == 0 || atomicNumber > maximumAtomicNumber) return {0.0, 0.0};

  const std::array<double, 2>& correction = anomalousCoefficients[atomicNumber][static_cast<std::size_t>(anode)];
  return {correction[0], correction[1]};
}
